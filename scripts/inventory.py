#!/usr/bin/env python3
"""inventory.py — every object Corpus runs on, one row each, with its purpose and who reads and writes it.

    python scripts/inventory.py              # write the CSV and its page into the share
    python scripts/inventory.py --out DIR    # write them somewhere else (a preview)

**Strategic review 9, R166.** Writes `inventory-corpus.csv` and `inventory-corpus.html` to the share's
`documentation/` (OSINT reads it as `X:\\documentation\\`). Regenerated by every cycle (`CYCLE.md`
step 7a) and never edited: a wrong row is fixed at the object it describes. OSINT's R167 writes
`inventory-osint.csv` in the same columns:

- `object` — the path from the repository root; a folder ends in `/`.
- `kind` — `process` (a root runbook), `script`, `test`, `lookup`, `log`, `queue` (a log a runbook
  works down), `document` (`documentation/`, `maturity/documentation/`, `content/`, the root's other
  markdown), `worker`.
- `purpose` — one line from the object itself: a script's docstring, a markdown file's `description:`
  or first heading, a folder's `README.md`. A CSV carries none of its own, so its purpose is the line
  that defines it elsewhere, of the shape `` `name.csv` — text `` or `` `name.csv`: text ``, in the
  script that writes it. Empty when none is found; R168's lint fails it.
- `purpose_from` — where that line was found.
- `read_by`, `written_by` — the scripts, runbooks and documents that name the object, split by whether a
  line naming it also speaks of writing (write, append, add, save, record, open for `w` or `a`).
  A heuristic: it decides the column, not whether a reference exists.

The walk does not enter the study folders under `maturity/` (250,000 working files), `outputs/`,
`site/` or `build/`: those are products, listed under the objects that make them.
"""
from __future__ import annotations

import argparse
import csv
import html
import io
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from status_lib import EXCHANGE  # noqa: E402

COLUMNS = ["object", "kind", "purpose", "purpose_from", "read_by", "written_by"]

# Logs that a runbook works down, oldest first, until empty: a queue, not a record.
QUEUES = {"logs/budget-followups.md", "logs/link-dead/",
          "logs/requests-for-osint.csv"}

# Folders whose files cannot state a purpose themselves (a CSV has no docstring) keep one line each
# in a README; that line is the file's purpose, and the README is not counted as a reader.
INDEXES = ("lookups/README.md", "logs/README.md")
TEXT = {".py", ".md", ".yml", ".yaml", ".js", ".mjs", ".toml", ".bat", ".ps1", ".txt", ".json", ".html"}
WRITE = re.compile(r"\bwrit(?:e|es|ten|ing)\b|\bappend|\badds?\b|\bsav(?:e|es|ed)\b|\brecords?\b|\bdump"
                   r"|open\([^)]*['\"][wa]b?['\"]|mode=['\"][wa]|>>|\.to_csv|csv\.writer|DictWriter|write_text",
                   re.I)
# A line that defines a data file: `- `lookups/x.csv` — what it is.` or the same with a colon, at the
# start of a line or list item; the purpose runs to the end of that sentence, across wrapped lines.
DEFINES = (r"^[ \t]*(?:[-*][ \t]+)?(?:\*\*)?`(?:[\w./-]*/)?{name}/?`(?:\*\*)?[ \t]*(?:—|–|:)[ \t]*"
           r"([^\n].{{10,280}}?)(?:\.(?=\s)|\n[ \t]*\n|\Z)")


def objects() -> list[tuple[str, str]]:
    """(path, kind) for every object, paths relative to ROOT with forward slashes."""
    out: list[tuple[str, str]] = []
    for p in sorted(ROOT.glob("*.md")):
        upper = p.stem.isupper() and p.stem not in ("README", "CLAUDE")
        out.append((p.name, "process" if upper else "document"))
    for folder in ("documentation", "maturity/documentation", "content"):
        out += [(p.relative_to(ROOT).as_posix(), "document") for p in sorted((ROOT / folder).glob("*.md"))]
    for p in sorted((ROOT / "scripts").iterdir()):
        if p.name == "__pycache__" or p.name.startswith("."):
            continue
        rel = p.relative_to(ROOT).as_posix() + ("/" if p.is_dir() else "")
        out.append((rel, "test" if p.name.startswith("test_") else "script"))
    for p in sorted((ROOT / "workers").iterdir()):
        out.append((p.relative_to(ROOT).as_posix() + "/", "worker"))
    for p in sorted((ROOT / "lookups").iterdir()):
        if p.name != "README.md":  # the folder's index of purposes, not an object
            out.append((p.relative_to(ROOT).as_posix(), "lookup"))
    for p in sorted((ROOT / "logs").iterdir()):
        if p.name.startswith(".") or p.name == "README.md":
            continue
        rel = p.relative_to(ROOT).as_posix() + ("/" if p.is_dir() else "")
        out.append((rel, "queue" if rel in QUEUES else "log"))
    for p in (ROOT / ".github" / "workflows").glob("*.yml"):
        out.append((p.relative_to(ROOT).as_posix(), "script"))
    return out


def referrers() -> dict[str, str]:
    """Every text file whose words can name an object: path -> text."""
    files: list[Path] = list(ROOT.glob("*.md")) + list(ROOT.glob("*.bat"))
    files += [ROOT / i for i in INDEXES]
    for folder in ("documentation", "maturity/documentation", "content"):
        files += (ROOT / folder).glob("*.md")
    # The R&D register and its pilots' notes name the scripts and designs a sitting uses.
    files += [p for p in (ROOT / "R&D").rglob("*.md") if "cache" not in p.parts]
    for folder in ("scripts", "workers", ".github/workflows"):
        # Prune before descending: `scripts/.workroot` is a junction into OSINT (300,000 files).
        for here, dirs, names in os.walk(ROOT / folder):
            dirs[:] = [d for d in dirs if not d.startswith(".") and d not in ("__pycache__", "node_modules")]
            files += [Path(here) / n for n in names if Path(n).suffix in TEXT]
    out = {}
    for p in files:
        try:
            rel = p.relative_to(ROOT).as_posix()
            if rel != "scripts/inventory.py":  # its own docstring names what it looks for
                out[rel] = p.read_text(encoding="utf-8", errors="replace")
        except OSError:
            pass
    return out


TOKEN = re.compile(r"(?<![\w.-])([\w][\w.-]*\w)(?![\w-])")
# A name built at run time, `study-ladder-{sid}.py`: each placeholder stands for a slug.
TEMPLATE = re.compile(r"(?<![\w.{}-])([\w-]*\{\w*\}[\w{}-]*\.[a-z]{2,4})(?![\w-])")
IMPORT = re.compile(r"\b(?:import|from)\s+(\w+)")


def token_index(texts: dict[str, str]) -> dict[str, list[tuple[str, str]]]:
    """token -> [(referrer, line)], once per referrer and line. Imports are keyed `import NAME`."""
    out: dict[str, list[tuple[str, str]]] = {}
    for ref, text in texts.items():
        for ln in text.splitlines():
            keys = set(TOKEN.findall(ln)) | {"import " + m for m in IMPORT.findall(ln)}
            keys |= {"template " + t for t in TEMPLATE.findall(ln)}
            for k in keys:
                out.setdefault(k, []).append((ref, ln))
    return out


def literal_word(template: str) -> bool:
    """A template counts only with a literal word of four letters besides the extension:
    `{name}.py` would otherwise name every script."""
    return bool(re.search(r"[A-Za-z]{4}", re.sub(r"\{\w*\}|\.[a-z]+$", "", template)))


def first_line(text: str) -> str:
    return re.sub(r"\s+", " ", text.strip().splitlines()[0]).strip() if text.strip() else ""


def strip_name(line: str, name: str) -> str:
    """`foo.py — does x` -> `does x`."""
    line = re.sub(rf"^`?{re.escape(name)}`?\s*(?:—|–|-|:)\s*", "", line)
    return line.strip().rstrip(".") + "." if line.strip() else ""


def own_purpose(path: Path) -> str:
    """The purpose the object states itself, or ''."""
    if path.is_dir():
        readme = path / "README.md"
        return own_purpose(readme) if readme.exists() else ""
    try:
        text = path.read_text(encoding="utf-8-sig", errors="replace")
    except OSError:
        return ""
    if path.suffix == ".py":
        m = re.match(r'(?:#[^\n]*\n|[ \t]*\r?\n)*[ \t]*[rRuU]?(?:"""|\'\'\')(.*?)(?:"""|\'\'\')', text, re.S)
        return strip_name(first_line(m.group(1)), path.name) if m else ""
    if path.suffix in (".md",):
        body = text
        fm = re.match(r"---\n(.*?)\n---\n", text, re.S)
        if fm:
            d = re.search(r"^description:\s*(.+)$", fm.group(1), re.M)
            if d:
                return d.group(1).strip().strip("'\"")
            body = text[fm.end():]
        body = re.sub(r"<!--.*?-->", "", body, flags=re.S)
        for line in body.splitlines():
            line = line.strip()
            if line:  # a heading or a sentence; a log's first entry is not a purpose
                return "" if line[0] in "-*|>" else re.sub(r"^#+\s*", "", line)
        return ""
    if path.name.endswith("-FROM"):
        return "The upstream commit this copy of a shared asset was taken from."
    if path.suffix in (".yml", ".yaml"):
        m = re.search(r"^name:\s*(.+)$", text, re.M)
        if m:
            return m.group(1).strip()
    if path.suffix in (".yml", ".yaml", ".js", ".mjs", ".bat", ".ps1", ".toml"):
        for line in text.splitlines():
            m = re.match(r"\s*(?:#|//|::|REM\b|rem\b)\s*(.+)", line)
            if m:
                return m.group(1).strip()
            if line.strip():
                return ""
    return ""


def names_of(rel: str) -> list[str]:
    """The tokens a referrer uses to name an object."""
    base = rel.rstrip("/").rsplit("/", 1)[-1]
    out = [base]
    if base.endswith(".py") and "-" not in base:
        out.append(base[:-3])  # imported as a module
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=Path(EXCHANGE) / "documentation")
    args = ap.parse_args()

    texts = referrers()
    index = token_index(texts)
    templates = [(re.compile(re.sub(r"\\\{\w*\\\}", lambda _: r"[\w-]+", re.escape(k[9:]))), v)
                 for k, v in index.items() if k.startswith("template ") and literal_word(k[9:])]
    rows = []
    for rel, kind in objects():
        path = ROOT / rel.rstrip("/")
        names = names_of(rel)
        purpose, source = own_purpose(path), rel
        if not purpose:
            source = ""
        read_by, written_by = [], []
        found: dict[str, list[str]] = {}
        for ref, ln in index.get(names[0], []):
            found.setdefault(ref, []).append(ln)
        if len(names) > 1:  # a bare module name only counts as an import
            for ref, ln in index.get("import " + names[1], []):
                found.setdefault(ref, []).append(ln)
        for pattern, refs in templates:
            if pattern.fullmatch(names[0]):
                for ref, ln in refs:
                    found.setdefault(ref, []).append(ln)
        index_file = rel.split("/")[0] + "/README.md"
        for ref, hits in sorted(found.items(), key=lambda kv: (kv[0] != index_file, kv[0])):
            if ref == rel or (rel.endswith("/") and ref.startswith(rel)):
                continue
            if ref not in INDEXES:  # a folder's index of purposes names everything and uses nothing
                (written_by if any(WRITE.search(h) for h in hits) else read_by).append(ref)
            if not purpose:
                m = re.compile(DEFINES.format(name=re.escape(names[0])), re.M | re.S).search(texts[ref])
                if m and not m.group(1).startswith("`"):  # a column list is not a purpose
                    purpose, source = re.sub(r"\s+", " ", m.group(1)).strip().rstrip(".") + ".", ref
        rows.append({"object": rel, "kind": kind, "purpose": purpose[:300], "purpose_from": source,
                     "read_by": "; ".join(sorted(read_by)), "written_by": "; ".join(sorted(written_by))})

    args.out.mkdir(parents=True, exist_ok=True)
    buf = io.StringIO()
    w = csv.DictWriter(buf, fieldnames=COLUMNS, lineterminator="\n")
    w.writeheader()
    w.writerows(rows)
    (args.out / "inventory-corpus.csv").write_bytes(buf.getvalue().encode("utf-8"))
    (args.out / "inventory-corpus.html").write_bytes(page(rows).encode("utf-8"))
    missing = sum(1 for r in rows if not r["purpose"])
    orphans = sum(1 for r in rows if not r["read_by"] and not r["written_by"])
    print(f"inventory: {len(rows)} objects, {missing} without a purpose, {orphans} named nowhere "
          f"-> {args.out / 'inventory-corpus.csv'}")
    return 0


def page(rows: list[dict]) -> str:
    """One sortable, filterable page: click a heading to sort, type to filter."""
    head = "".join(f"<th>{c.replace('_', ' ')}</th>" for c in COLUMNS)
    body = "\n".join("<tr>" + "".join(f"<td>{html.escape(r[c]).replace('; ', '<br>')}</td>" for c in COLUMNS)
                     + "</tr>" for r in rows)
    return f"""<!doctype html>
<html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>Corpus inventory</title>
<style>
body{{font:14px/1.4 system-ui,sans-serif;margin:1rem;color:#222}}
input{{font:inherit;padding:.3rem;width:20rem;margin-bottom:.6rem}}
table{{border-collapse:collapse;width:100%}}
th,td{{border-bottom:1px solid #ddd;padding:.3rem .5rem;vertical-align:top;text-align:left}}
th{{position:sticky;top:0;background:#f4f4f4;cursor:pointer;white-space:nowrap}}
td:first-child{{font-family:ui-monospace,monospace;white-space:nowrap}}
td:nth-child(5),td:nth-child(6){{font-size:12px;color:#555}}
</style></head><body>
<h1>Corpus inventory</h1>
<p>{len(rows)} objects. Written by <code>scripts/inventory.py</code> each cycle; never edited.
Click a heading to sort; type to filter.</p>
<input id="q" placeholder="Filter" autofocus>
<table id="t"><thead><tr>{head}</tr></thead><tbody>
{body}
</tbody></table>
<script>
const t=document.getElementById('t'),tb=t.tBodies[0];
document.getElementById('q').oninput=e=>{{const q=e.target.value.toLowerCase();
for(const r of tb.rows)r.hidden=q&&!r.textContent.toLowerCase().includes(q);}};
t.tHead.onclick=e=>{{const th=e.target.closest('th');if(!th)return;const i=th.cellIndex,
d=th.dataset.d=th.dataset.d==='1'?'-1':'1';const rs=[...tb.rows];
rs.sort((a,b)=>d*a.cells[i].textContent.localeCompare(b.cells[i].textContent));rs.forEach(r=>tb.append(r));}};
</script></body></html>
"""


if __name__ == "__main__":
    sys.exit(main())
